-- AgentHub AI 模块建表脚本（MySQL 8.0）
-- 40 张 ai_ 表，全部语句幂等，可重复执行。表名与列名同 PostgreSQL 版严格一致。
-- 审计口径：业务表带 del_flag 软删；关联表与审计/日志表为物理删（§12.4 清理不引入软删）。
-- 字符集不指定 collation，随库继承底座默认，避免与 sys_ 表跨库比较冲突。

create table if not exists ai_model_config (
    id              bigint          not null,
    model_code      varchar(64)     not null,
    model_name      varchar(128)    not null,
    provider        varchar(64),
    model_type      varchar(32)     not null,
    base_url        varchar(512),
    api_key_cipher  varchar(1024),
    temperature     decimal(4,2),
    max_tokens      int,
    context_length  int,
    param_json      text,
    status          char(1)         not null default '0',
    remark          varchar(500),
    create_dept     bigint,
    create_by       bigint,
    create_time     datetime,
    update_by       bigint,
    update_time     datetime,
    del_flag        char(1)         not null default '0',
    primary key (id),
    key idx_ai_model_config_type (model_type, status),
    key idx_ai_model_config_code (model_code)
) engine=innodb default charset=utf8mb4 comment='模型配置：对话/向量/重排/视觉四类接入';

